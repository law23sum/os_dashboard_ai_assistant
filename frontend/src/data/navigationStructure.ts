// Helper to get features sorted by complexity
export function getFeaturesSortedByComplexity(platform: NavigationPlatform): NavigationFeature[] {
  const complexityOrder = { simple: 0, intermediate: 1, complex: 2, advanced: 3 }
  return [...platform.features].sort(
    (a, b) => complexityOrder[a.complexity] - complexityOrder[b.complexity]
  )
}

// Helper to find platform by path
export function findPlatformByPath(path: string): NavigationPlatform | null {
  for (const category of navigationStructure) {
    for (const platform of category.platforms) {
      if (platform.path === path) {
        return platform
      }
    }
  }
  return null
}

// Helper to find category by platform path
export function findCategoryByPlatformPath(path: string): NavigationCategory | null {
  for (const category of navigationStructure) {
    for (const platform of category.platforms) {
      if (platform.path === path) {
        return category
      }
    }
  }
  return null
}
